const BY_CODE: Map<string, Country> = new Map(
  COUNTRIES.map((c) => [c.code, c]),
);

/** Look up a country by alpha-2 code (case-insensitive). */
export function countryByCode(code: string | null | undefined): Country | null {
  if (!code) return null;
  return BY_CODE.get(code.trim().toUpperCase()) ?? null;
}

/** True when `code` is a recognised country in the dataset. */
export function isValidCountryCode(code: string | null | undefined): boolean {
  return countryByCode(code) !== null;
}
