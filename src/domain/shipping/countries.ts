/**
 * Canonical ISO 3166-1 country/territory dataset for worldwide shipping.
 *
 * This is the single source of truth for the *set* of shippable places. The
 * database (`shipping_countries`) is seeded from it, so runtime code can read
 * flags/zones/names without a DB round-trip, and admins toggle availability and
 * rates per country in the DB.
 *
 * Flags are derived from the alpha-2 code (Unicode regional-indicator letters),
 * so there are no image assets to load.
 */

export type ShippingZone =
  | "Africa"
  | "Europe"
  | "Asia"
  | "North America"
  | "South America"
  | "Oceania"
  | "Antarctica";

export const SHIPPING_ZONES: ShippingZone[] = [
  "Africa",
  "Europe",
  "Asia",
  "North America",
  "South America",
  "Oceania",
  "Antarctica",
];

export interface Country {
  /** ISO 3166-1 alpha-2 code (uppercase). */
  readonly code: string;
  readonly name: string;
  readonly zone: ShippingZone;
}

/** Turn an alpha-2 code into its flag emoji (e.g. "NG" → 🇳🇬). */
export function flagEmoji(code: string): string {
  const cc = code.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(cc)) return "🏳️";
  return String.fromCodePoint(
    ...[...cc].map((c) => 0x1f1e6 - 65 + c.charCodeAt(0)),
  );
}

